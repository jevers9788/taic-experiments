"""Build results/baselines.{csv,md} from results/<gpu>/<Kernel>.json. No hand-entered numbers."""
import csv
import json
import re
from pathlib import Path

GPUS = ['L4', 'T4', 'V100']
STOCK = ['torch_mm_cublas', 'torch_sdpa_output_only', 'torch_upcast_fp16_mm', 'torch_scaled_mm_fp8',
         'torch_upcast_fp16_mv']
COLUMNS = ['gpu', 'kernel', 'status', 'triton_compiles', 'triton_p50_ms', 'pytorch_p50_ms',
           'best_stock', 'best_stock_p50_ms', 'triton_pct_copy_bw', 'triton_pct_fp16_mm',
           'source', 'notes']


def kernels():
    # Parse the list instead of importing baselines.py (which needs torch).
    text = (Path(__file__).parent / 'baselines.py').read_text()
    block = text[text.index('KERNELS = ['):text.index(']', text.index('KERNELS = ['))]
    return re.findall(r"'(\w+)'", block)


def p50(impl):
    if impl and impl.get('correct') and 'timing_ms' in impl:
        return impl['timing_ms']['p50']
    return None


def row(gpu, kernel, root):
    path = root / gpu.lower() / f'{kernel}.json'
    if not path.exists():
        return {'gpu': gpu, 'kernel': kernel, 'status': 'not_run', 'notes': 'no logged run'}
    record = json.loads(path.read_text())
    impls = record['implementations']
    triton = impls.get('triton')
    stock = {k: p50(impls.get(k)) for k in STOCK if p50(impls.get(k)) is not None}
    best = min(stock, key=stock.get) if stock else ''
    roof = (triton or {}).get('roofline', {})
    notes = []
    if 'autotune_error' in record:
        notes.append('Triton failed: ' + record['autotune_error'].strip().splitlines()[-1][:120])
    elif triton and not triton.get('correct'):
        notes.append('Triton incorrect vs independent reference')
    for label, impl in impls.items():
        if label != 'triton' and not impl.get('correct'):
            notes.append(f'{label} failed')
    return {
        'gpu': gpu, 'kernel': kernel,
        'status': 'measured' if p50(triton) else 'triton_failed',
        'triton_compiles': 'autotune_error' not in record,
        'triton_p50_ms': p50(triton), 'pytorch_p50_ms': p50(impls.get('pytorch_eager')),
        'best_stock': best, 'best_stock_p50_ms': stock.get(best),
        'triton_pct_copy_bw': roof.get('pct_of_measured_copy_bw'),
        'triton_pct_fp16_mm': roof.get('pct_of_measured_fp16_mm'),
        'source': str(path), 'notes': '; '.join(notes),
    }


def fmt(value):
    return f'{value:.4g}' if isinstance(value, float) else ('' if value is None else str(value))


def main(root=Path('results')):
    rows = [row(gpu, k, root) for gpu in GPUS for k in kernels()]
    with open(root / 'baselines.csv', 'w', newline='') as f:
        writer = csv.DictWriter(f, COLUMNS)
        writer.writeheader()
        writer.writerows({c: fmt(r.get(c)) for c in COLUMNS} for r in rows)
    lines = ['# Baselines', '',
             'Generated by `scripts/make_table.py` from per-run JSON (see `source`). '
             'Empty cells are missing data, not zeros. % columns compare against ceilings '
             'measured on the same card in the same run (device copy, cuBLAS FP16 mm); '
             'traffic is a compulsory-bytes lower bound.', '',
             '| ' + ' | '.join(COLUMNS[:-2]) + ' | notes |',
             '|' + '---|' * (len(COLUMNS) - 1)]
    lines += ['| ' + ' | '.join(fmt(r.get(c)) for c in COLUMNS if c != 'source') + ' |' for r in rows]
    (root / 'baselines.md').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
